import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:pro_companion_core/core.dart';
import 'package:test/test.dart';

/// #68 criterion 5: the running-order rule against the committed vectors in
/// fixtures/rounding/, rounding logs with their expected order worked out by
/// hand. pro-companion is canonical for them and burgee vendors them, so this
/// also refuses a set whose SHA256SUMS no longer matches its bytes.
///
/// Read from this repository's checkout, synchronously; the rule is pure, so
/// nothing here reaches a network.

/// fixtures/rounding/ at the repo root, from packages/core where `dart test`
/// runs.
const vectorDir = '../../fixtures/rounding';
const manifestName = 'SHA256SUMS';
const vectorFormat = 'pro-companion-running-order-vector/1';
final sumLine = RegExp(r'^([0-9a-f]{64})  (\S+)$');

String baseName(FileSystemEntity f) => f.uri.pathSegments.last;

List<File> vectorFiles() => Directory(vectorDir)
    .listSync()
    .whereType<File>()
    .where((f) => f.path.endsWith('.json'))
    .toList()
  ..sort((a, b) => a.path.compareTo(b.path));

/// A vector's event as the rule reads it: the envelope fields the format
/// carries, with the rest at their plainest.
EventEnvelope eventOf(Map<String, dynamic> e) => EventEnvelope(
      ulid: e['ulid'] as String,
      deviceId: e['device_id'] as String,
      seq: e['seq'] as int,
      deviceTs: e['device_ts'] as int,
      kind: e['kind'] as String,
      correctsUlid: e['corrects_ulid'] as String?,
      payload: Map<String, Object?>.from(e['payload'] as Map),
      source: 'tap',
      payloadVersion: 1,
    );

/// What a vector's `expected` says, in the shape it says it.
Map<String, Object?> asExpected(FleetRunningOrder o) => {
      'fleet': o.fleet,
      'race': o.race,
      'order': [
        for (final e in o.entries) {'sail': e.sail, 'roundings': e.roundings, 'mark': e.mark},
      ],
      'unnamed': o.unnamed,
      'waiting': o.waiting,
      'clocks_unmatched': o.clocksUnmatched,
    };

void main() {
  final files = vectorFiles();

  test('SHA256SUMS lists exactly the files here, each with its current hash', () {
    final listed = <String, String>{};
    for (final line in File('$vectorDir/$manifestName').readAsLinesSync()) {
      if (line.isEmpty) continue;
      final m = sumLine.firstMatch(line);
      expect(m, isNotNull, reason: 'not a `sha256sum --text` line: "$line"');
      listed[m!.group(2)!] = m.group(1)!;
    }
    final present = {
      for (final f in Directory(vectorDir).listSync().whereType<File>())
        if (baseName(f) != manifestName) baseName(f),
    };
    expect(listed.keys.toSet(), present, reason: 'SHA256SUMS must list exactly the files here');
    listed.forEach((name, hash) {
      expect(sha256.convert(File('$vectorDir/$name').readAsBytesSync()).toString(), hash,
          reason: '$name changed without SHA256SUMS');
    });
    expect(files, isNotEmpty, reason: 'a loader that finds nothing cannot pass by checking nothing');
  });

  test('the README states the direction and that orders are worked out by hand', () {
    final readme = File('$vectorDir/README.md').readAsStringSync();
    expect(readme, contains('pro-companion is canonical'));
    expect(readme, contains('burgee vendors'));
    expect(readme, contains('never generated by the Dart rule'));
  });

  test('every criterion the vectors stand for has one, and each says how it was worked', () {
    final criteria = <String>{};
    for (final f in files) {
      final v = jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
      expect(v['format'], vectorFormat, reason: baseName(f));
      expect('${v['name']}.json', baseName(f), reason: 'name matches the file');
      expect(v['working'], isA<List>().having((w) => w.length, 'lines', greaterThan(0)), reason: baseName(f));
      criteria.add(v['criterion'] as String);
    }
    expect(criteria, containsAll(['#68 criterion 1', '#68 criterion 2', '#68 criterion 3', '#68 criterion 4']));
  });

  group('the running-order vectors (#68 criterion 5)', () {
    for (final f in files) {
      test(baseName(f), () {
        final v = jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
        final events = [for (final e in v['events'] as List) eventOf(e as Map<String, dynamic>)];
        final actual = [for (final o in runningOrders(events, now: v['now'] as int)) asExpected(o)];
        expect(actual, v['expected']);
      });
    }
  });
}
